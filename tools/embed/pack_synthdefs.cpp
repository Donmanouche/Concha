// Compiles a folder of .scsyndef files (and its index.json) into a C++ source:
//   concha_pack_synthdefs <dir> <out.cpp>
// defining concha::sc::embeddedSynthDefs() (name, bytes) and embeddedSynthDefIndex() (the JSON).
#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

namespace fs = std::filesystem;

static std::string bytes(const std::vector<unsigned char>& d)
{
    std::string out;
    for (size_t i = 0; i < d.size(); ++i) {
        out += std::to_string(int(d[i]));
        out += i % 32 == 31 ? ",\n" : ",";
    }
    return out;
}

int main(int argc, char** argv)
{
    if (argc != 3) {
        std::fprintf(stderr, "usage: %s <dir> <out.cpp>\n", argv[0]);
        return 2;
    }
    std::vector<fs::path> files;
    for (const auto& e : fs::directory_iterator(argv[1]))
        if (e.path().extension() == ".scsyndef") files.push_back(e.path());
    std::sort(files.begin(), files.end());
    auto read = [](const fs::path& p) {
        std::ifstream f(p, std::ios::binary);
        return std::vector<unsigned char>((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
    };
    std::string out = "// Generated by tools/embed/pack_synthdefs.cpp. Do not edit.\n#include <cstddef>\n#include <string_view>\n"
                      "#include <utility>\n#include <vector>\n\nnamespace concha::sc {\nnamespace {\n";
    for (size_t i = 0; i < files.size(); ++i)
        out += "const unsigned char kDef" + std::to_string(i) + "[] = {" + bytes(read(files[i])) + "};\n";
    auto index = read(fs::path(argv[1]) / "index.json");
    index.push_back(0);
    out += "const unsigned char kIndex[] = {" + bytes(index) + "};\n} // namespace\n\n";
    out += "const std::vector<std::pair<std::string_view, std::string_view>>& embeddedSynthDefs()\n{\n"
           "    static const std::vector<std::pair<std::string_view, std::string_view>> defs = {\n";
    for (size_t i = 0; i < files.size(); ++i)
        out += "        {\"" + files[i].stem().string() + "\", {reinterpret_cast<const char*>(kDef" + std::to_string(i) +
               "), sizeof(kDef" + std::to_string(i) + ")}},\n";
    out += "    };\n    return defs;\n}\n\nstd::string_view embeddedSynthDefIndex() { return reinterpret_cast<const char*>(kIndex); }\n\n"
           "} // namespace concha::sc\n";
    std::ofstream(argv[2], std::ios::binary) << out;
    std::printf("packed %zu SynthDefs\n", files.size());
    return 0;
}
