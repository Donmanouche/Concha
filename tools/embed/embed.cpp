// Turns a file into a C++ source defining `std::string_view <ns>::<function>()`.
// usage: concha_embed <input> <output.cpp> <namespace> <function>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <string>
#include <vector>

int main(int argc, char** argv)
{
    if (argc != 5) {
        std::fprintf(stderr, "usage: %s <input> <output.cpp> <namespace> <function>\n", argv[0]);
        return 2;
    }
    std::ifstream in(argv[1], std::ios::binary);
    if (!in) {
        std::fprintf(stderr, "cannot read %s\n", argv[1]);
        return 1;
    }
    const std::vector<unsigned char> data((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
    std::string out;
    out.reserve(data.size() * 2 + 1024);
    out += "// Generated by tools/embed from ";
    out += argv[1];
    out += ". Do not edit.\n#include <string_view>\n\nnamespace ";
    out += argv[3];
    out += " {\nnamespace {\n// Split in chunks: some compilers limit the length of one string literal.\nconst char kData[] =\n\"";
    size_t col = 0;
    for (size_t i = 0; i < data.size(); ++i) {
        const unsigned char c = data[i];
        if (col > 4000 && c == '\n') {
            out += "\\n\"\n\"";
            col = 0;
            continue;
        }
        switch (c) {
            case '\\': out += "\\\\"; break;
            case '"': out += "\\\""; break;
            case '\n': out += "\\n"; break;
            case '\r': out += "\\r"; break;
            case '\t': out += "\\t"; break;
            case '?': out += "\\?"; break; // no trigraphs
            default:
                if (c < 0x20 || c >= 0x7f) {
                    char buf[8];
                    std::snprintf(buf, sizeof buf, "\\%03o", c);
                    out += buf;
                } else {
                    out += static_cast<char>(c);
                }
        }
        ++col;
    }
    out += "\";\n} // namespace\n\nstd::string_view ";
    out += argv[4];
    out += "() { return {kData, sizeof(kData) - 1}; }\n\n} // namespace ";
    out += argv[3];
    out += "\n";
    std::ofstream(argv[2], std::ios::binary) << out;
    return 0;
}
